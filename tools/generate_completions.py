"""
Generate static shell completion scripts (bash, zsh, fish) for every typer
app listed under `apps` in snap/snapcraft.yaml (+ [project.scripts] in
pyproject.toml).

Typer's built-in completion re-runs the python program on every <TAB>, which
is very slow in the snap and only works in bash through snapd's `completer`.
The scripts generated here are pure shell and mirror the click/typer parser.

Usage (from the repo root):
    uv run python tools/generate_completions.py          # regenerate
    uv run python tools/generate_completions.py --check  # verify up to date
"""

import argparse
import importlib
import re
import sys
import tomllib
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import typer
import typer.main
import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
SNAPCRAFT_YAML = REPO_ROOT / "snap" / "snapcraft.yaml"
PYPROJECT = REPO_ROOT / "pyproject.toml"
OUT_DIR = REPO_ROOT / "src" / "bugit_v2" / "completions"
BASH_FILE = OUT_DIR / "bugit.bash"
ZSH_FILE = OUT_DIR / "_bugit"
FISH_FILE = OUT_DIR / "bugit.fish"
# value of `completer:` in snapcraft.yaml, relative to $SNAP
SNAP_COMPLETER = BASH_FILE.relative_to(REPO_ROOT).as_posix()

# typer's own completion options don't work in the snap, the scripts here
# replace them
EXCLUDED_OPTS = {"--install-completion", "--show-completion"}
PY_APP_CMD = re.compile(r"^bin/python3 \$SNAP/src/(?P<path>[\w/]+)\.py$")
HEADER = "Generated by tools/generate_completions.py, DO NOT EDIT."


@dataclass
class Opt:
    names: list[str]
    help: str
    # None for flags, otherwise one of file/dir/choice/text
    kind: str | None
    metavar: str
    choices: list[str] = field(default_factory=list[str])
    multiple: bool = False


@dataclass
class Arg:
    name: str
    kind: str
    choices: list[str] = field(default_factory=list[str])
    variadic: bool = False


@dataclass
class Cmd:
    path: list[str]  # [root, sub, subsub...]
    help: str
    opts: list[Opt]
    args: list[Arg]
    subcommands: list["Cmd"]

    @property
    def key(self) -> str:
        return " ".join(self.path)


@dataclass
class Program:
    root: str  # snap app name, used as the root of every command path
    names: list[str]  # executable names to register completions for
    cmd: Cmd


def clean_help(text: str | None) -> str:
    if not text:
        return ""
    text = re.sub(r"\[/?[a-z ]*\]", "", text)  # rich markup like [yellow] [/]
    text = " ".join(text.split())
    first_sentence = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    return first_sentence.rstrip(".")


# typer may vendor its own copy of click (typer._click), so the classes are
# checked by duck typing instead of isinstance()


def value_kind(param_type: Any) -> str:
    if hasattr(param_type, "choices"):
        return "choice"
    if hasattr(param_type, "file_okay") and hasattr(param_type, "dir_okay"):
        return "dir" if (param_type.dir_okay and not param_type.file_okay) else "file"
    if param_type.name == "filename":  # click.File
        return "file"
    return "text"


def choices_of(param_type: Any) -> list[str]:
    return [str(c) for c in getattr(param_type, "choices", [])]


def build_cmd(command: Any, path: list[str], parent_ctx: Any = None) -> Cmd:
    # context_settings carries things like help_option_names=["-h", "--help"]
    ctx = command.context_class(
        command, parent=parent_ctx, info_name=path[-1], **command.context_settings
    )

    opts: list[Opt] = []
    args: list[Arg] = []
    for p in command.get_params(ctx):
        if p.param_type_name == "option":
            # sorted since click builds the help option's names from a set
            names = sorted(
                [*p.opts, *p.secondary_opts],
                key=lambda n: (n.startswith("--"), len(n), n),
            )
            if p.hidden or EXCLUDED_OPTS.intersection(names):
                continue
            is_flag = p.is_flag or p.count
            opts.append(
                Opt(
                    names=names,
                    help=clean_help(p.help),
                    kind=None if is_flag else value_kind(p.type),
                    metavar=(p.name or names[-1]).replace("_", "-"),
                    choices=choices_of(p.type),
                    multiple=bool(p.multiple or p.count),
                )
            )
        elif p.param_type_name == "argument":
            args.append(
                Arg(
                    name=(p.name or "arg").replace("_", "-"),
                    kind=value_kind(p.type),
                    choices=choices_of(p.type),
                    variadic=p.nargs == -1,
                )
            )

    subcommands: list[Cmd] = []
    if hasattr(command, "list_commands"):
        for name in command.list_commands(ctx):
            sub = command.get_command(ctx, name)
            if sub is None or sub.hidden:
                continue
            subcommands.append(build_cmd(sub, [*path, name], ctx))

    return Cmd(
        path=path,
        help=clean_help(command.get_short_help_str(limit=200)),
        opts=opts,
        args=args,
        subcommands=subcommands,
    )


def find_typer_app(module_name: str, attr: str | None = None) -> typer.Typer:
    module = importlib.import_module(module_name)
    if attr is not None:
        app = getattr(module, attr)
        assert isinstance(app, typer.Typer), f"{module_name}:{attr} is not typer"
        return app
    apps = [v for v in vars(module).values() if isinstance(v, typer.Typer)]
    if len(apps) != 1:
        raise RuntimeError(f"Expected exactly 1 typer app in {module_name}")
    return apps[0]


def collect_programs() -> tuple[list[Program], list[str]]:
    """
    :return: (programs, errors about the snapcraft.yaml completer settings)
    """
    snapcraft = yaml.safe_load(SNAPCRAFT_YAML.read_text())
    pyproject = tomllib.loads(PYPROJECT.read_text())
    snap_name: str = snapcraft["name"]
    scripts: dict[str, str] = pyproject.get("project", {}).get("scripts", {})

    programs: list[Program] = []
    errors: list[str] = []
    for app_name, app_def in snapcraft["apps"].items():
        if not (m := PY_APP_CMD.match(app_def.get("command", ""))):
            continue
        typer_app = find_typer_app(m["path"].replace("/", "."))

        names = [snap_name if app_name == snap_name else f"{snap_name}.{app_name}"]
        for script_name, target in scripts.items():
            mod, _, attr = target.partition(":")
            if find_typer_app(mod, attr or None) is typer_app:
                names.append(script_name)

        if app_def.get("completer") != SNAP_COMPLETER:
            errors.append(
                f"snapcraft.yaml: app '{app_name}' should have "
                + f"'completer: {SNAP_COMPLETER}'"
            )

        command = typer.main.get_command(typer_app)
        programs.append(Program(app_name, names, build_cmd(command, [app_name])))

    return programs, errors


def walk(cmd: Cmd) -> Iterator[Cmd]:
    yield cmd
    for sub in cmd.subcommands:
        yield from walk(sub)


def all_names(programs: list[Program]) -> str:
    return " ".join(n for p in programs for n in p.names)


def sq(s: str) -> str:
    """Single quote for bash/zsh"""
    return "'" + s.replace("'", "'\\''") + "'"


# ----------------------------------- bash -----------------------------------


def gen_bash(programs: list[Program]) -> str:
    spec_cases: list[str] = []
    choice_cases: list[str] = []
    for prog in programs:
        for cmd in walk(prog.cmd):
            subcmds = " ".join(s.path[-1] for s in cmd.subcommands)
            opts = " ".join(n for o in cmd.opts for n in o.names)
            valopts = " ".join(
                f"{n}={o.kind}" for o in cmd.opts if o.kind is not None for n in o.names
            )
            once = " ".join("|".join(o.names) for o in cmd.opts if not o.multiple)
            args = " ".join(a.kind + ("*" if a.variadic else "") for a in cmd.args)
            spec_cases.append(
                f"    {sq(cmd.key)})\n"
                + f"        subcmds={sq(subcmds)}\n"
                + f"        opts={sq(opts)}\n"
                + f"        valopts={sq(valopts)}\n"
                + f"        once={sq(once)}\n"
                + f"        args={sq(args)}\n"
                + "        ;;"
            )
            for o in cmd.opts:
                if o.choices:
                    keys = "|".join(sq(f"{cmd.key} {n}") for n in o.names)
                    values = " ".join(map(sq, o.choices))
                    choice_cases.append(f"    {keys}) printf '%s\\n' {values} ;;")
            for i, a in enumerate(cmd.args):
                if a.choices:
                    values = " ".join(map(sq, a.choices))
                    choice_cases.append(
                        f"    {sq(f'{cmd.key} #{i}')}) printf '%s\\n' {values} ;;"
                    )

    prog_cases = "\n".join(
        f"    {'|'.join(map(sq, p.names))}) path={sq(p.root)} ;;" for p in programs
    )
    spec_body = "\n".join(spec_cases)
    choice_body = "\n".join(choice_cases) or "    *) ;;"

    return f"""\
# shellcheck shell=bash
# {HEADER}
#
# This is the snap's bash `completer`. To skip the `snap run` overhead on
# every <TAB>, it can also be sourced directly: source <(bugit.completion bash)

# _bugit_spec <path>: sets subcmds, opts, valopts, once, args of a command
_bugit_spec() {{
    case "$1" in
{spec_body}
    *) subcmds='' opts='' valopts='' once='' args='' ;;
    esac
}}

# _bugit_choices <path> <option or #arg_index>
_bugit_choices() {{
    case "$1 $2" in
{choice_body}
    esac
}}

# _bugit_valkind <option>: sets kind if <option> takes a value
_bugit_valkind() {{
    local e
    for e in $valopts; do
        if [[ ${{e%%=*}} == "$1" ]]; then
            kind=${{e#*=}}
            return 0
        fi
    done
    return 1
}}

# _bugit_is_used <option>: true if a non-repeatable option was already given
_bugit_is_used() {{
    local g m
    for g in $once; do
        [[ "|$g|" == *"|$1|"* ]] || continue
        for m in ${{g//|/ }}; do
            [[ $used == *" $m "* ]] && return 0
        done
        return 1
    done
    return 1
}}

# _bugit_value <kind> <path> <option or #arg_index>
_bugit_value() {{
    case "$1" in
    # empty reply + "-o default" makes the calling shell complete the path,
    # so it's done on the host instead of inside the snap's mount namespace
    file) compopt -o default ;;
    dir) compopt -o dirnames ;;
    choice) mapfile -t COMPREPLY < <(compgen -W "$(_bugit_choices "$2" "$3")" -- "$cur") ;;
    esac
}}

_bugit_complete() {{
    local IFS=$' \\t\\n'
    local cur words cword
    COMPREPLY=()
    if declare -F _get_comp_words_by_ref >/dev/null 2>&1; then
        _get_comp_words_by_ref -n =: -c cur -w words -i cword
    else
        words=("${{COMP_WORDS[@]}}")
        cword=$COMP_CWORD
        cur=${{COMP_WORDS[COMP_CWORD]}}
    fi

    local path
    case "${{words[0]##*/}}" in
{prog_cases}
    *) return 0 ;;
    esac

    local subcmds opts valopts once args kind=''
    _bugit_spec "$path"

    local i w expect='' used=' ' npos=0 endopts=0
    for ((i = 1; i < cword; i++)); do
        w=${{words[i]}}
        if [[ -n $expect ]]; then
            expect=''
            continue
        fi
        if ((!endopts)) && [[ $w == -- ]]; then
            endopts=1
            continue
        fi
        if ((!endopts)) && [[ $w == -?* ]]; then
            used+="${{w%%=*}} "
            if [[ $w != *=* ]] && _bugit_valkind "$w"; then
                expect=$w
            fi
            continue
        fi
        if ((npos == 0)) && [[ -n $subcmds && " $subcmds " == *" $w "* ]]; then
            path+=" $w"
            _bugit_spec "$path"
            used=' '
            continue
        fi
        ((npos++))
    done

    # value of an option: "--opt <TAB>" or "--opt=<TAB>"
    if [[ -n $expect ]]; then
        _bugit_value "$kind" "$path" "$expect"
        return 0
    fi
    if ((!endopts)) && [[ $cur == --*=* ]] && _bugit_valkind "${{cur%%=*}}"; then
        local opt=${{cur%%=*}}
        cur=${{cur#*=}}
        _bugit_value "$kind" "$path" "$opt"
        return 0
    fi

    if ((!endopts)) && [[ $cur == -* ]]; then
        local o candidates=()
        for o in $opts; do
            _bugit_is_used "$o" || candidates+=("$o")
        done
        mapfile -t COMPREPLY < <(compgen -W "${{candidates[*]}}" -- "$cur")
        return 0
    fi

    if [[ -n $subcmds ]]; then
        ((npos == 0)) && mapfile -t COMPREPLY < <(compgen -W "$subcmds" -- "$cur")
        return 0
    fi

    local a j=0
    for a in $args; do
        if [[ $a == *'*' ]] || ((j == npos)); then
            _bugit_value "${{a%'*'}}" "$path" "#$j"
            return 0
        fi
        ((j++))
    done
    return 0
}}

complete -F _bugit_complete {all_names(programs)}
"""


# ----------------------------------- zsh ------------------------------------


def zsh_func(cmd: Cmd) -> str:
    return "_bugit__" + "__".join(re.sub(r"\W", "_", p) for p in cmd.path)


def zsh_escape(s: str) -> str:
    for c in "\\[]:":
        s = s.replace(c, "\\" + c)
    return s


def zsh_action(kind: str, choices: list[str]) -> str:
    match kind:
        case "file":
            return "_files"
        case "dir":
            return "_files -/"
        case "choice":
            return "(" + " ".join(c.replace(" ", "\\ ") for c in choices) + ")"
        case _:
            return " "


def zsh_opt_spec(o: Opt) -> str:
    prefix = "*" if o.multiple else "(" + " ".join(o.names) + ")"
    # "--opt=" lets zsh accept both "--opt value" and "--opt=value"
    names = [n + "=" if (o.kind and n.startswith("--")) else n for n in o.names]
    tail = f"[{zsh_escape(o.help)}]" if o.help else ""
    if o.kind is not None:
        tail += f":{zsh_escape(o.metavar)}:{zsh_action(o.kind, o.choices)}"
    if len(names) == 1:
        return sq(("*" if o.multiple else "") + names[0] + tail)
    return sq(prefix) + "{" + ",".join(names) + "}" + sq(tail)


def zsh_arguments(specs: list[str], flags: str = "") -> list[str]:
    return [
        f"    _arguments{flags} \\",
        *[f"        {s} \\" for s in specs[:-1]],
        f"        {specs[-1]}" + (" && ret=0" if flags else ""),
    ]


def gen_zsh_cmd(cmd: Cmd) -> str:
    specs = [zsh_opt_spec(o) for o in cmd.opts]
    lines = [f"{zsh_func(cmd)}() {{"]
    if cmd.subcommands:
        specs += ["': :->command'", "'*:: :->argument'"]
        described = [
            "            " + sq(f"{zsh_escape(s.path[-1])}:{s.help}")
            for s in cmd.subcommands
        ]
        dispatch = [
            f"        {sq(s.path[-1])}) {zsh_func(s)} && ret=0 ;;"
            for s in cmd.subcommands
        ]
        context = cmd.key.replace(" ", "-")
        lines += [
            "    local curcontext=$curcontext state state_descr line ret=1",
            "    typeset -A opt_args",
            *zsh_arguments(specs, " -C"),
            "    case $state in",
            "    command)",
            "        local -a commands=(",
            *described,
            "        )",
            "        _describe -t commands command commands && ret=0",
            "        ;;",
            "    argument)",
            f"        curcontext=${{curcontext%:*:*}}:{context}-$words[1]:",
            "        case $words[1] in",
            *dispatch,
            "        esac",
            "        ;;",
            "    esac",
            "    return ret",
        ]
    else:
        for a in cmd.args:
            action = zsh_action(a.kind, a.choices)
            specs.append(sq(("*" if a.variadic else "") + f":{a.name}:{action}"))
        if specs:
            lines += zsh_arguments(specs)
        else:
            lines.append("    _message 'no more arguments'")
    lines.append("}")
    return "\n".join(lines)


def gen_zsh(programs: list[Program]) -> str:
    funcs = "\n\n".join(gen_zsh_cmd(c) for p in programs for c in walk(p.cmd))
    dispatch = "\n".join(
        f"    {'|'.join(p.names)}) {zsh_func(p.cmd)} \"$@\" ;;" for p in programs
    )
    return f"""\
#compdef {all_names(programs)}
# {HEADER}
#
# Either put this file in a directory in $fpath (named "_bugit"), or source it
# after compinit, for example: source <(bugit.completion zsh)

{funcs}

_bugit() {{
    case $service in
{dispatch}
    esac
}}

if [[ $funcstack[1] == _bugit ]]; then
    # autoloaded from $fpath
    _bugit "$@"
else
    compdef _bugit {all_names(programs)}
fi
"""


# ----------------------------------- fish -----------------------------------


def fq(s: str) -> str:
    """Single quote for fish"""
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def fish_value_action(kind: str, choices: list[str]) -> str:
    match kind:
        case "file":
            return "-F"
        case "dir":
            return "-f -a '(__fish_complete_directories)'"
        case "choice":
            return f"-f -a {fq(' '.join(choices))}"
        case _:
            return "-f"


def fish_opt_flags(o: Opt) -> str:
    parts: list[str] = []
    for n in o.names:
        if n.startswith("--"):
            parts.append(f"-l {fq(n[2:])}")
        elif len(n) == 2:
            parts.append(f"-s {fq(n[1:])}")
        else:
            parts.append(f"-o {fq(n[1:])}")  # multi-char single dash like -cb
    if o.kind is not None:
        parts.append("-r " + fish_value_action(o.kind, o.choices))
    if o.help:
        parts.append(f"-d {fq(o.help)}")
    return " ".join(parts)


def gen_fish(programs: list[Program]) -> str:
    subcmd_cases: list[str] = []
    valopt_cases: list[str] = []
    completions: list[str] = []
    for prog in programs:
        for cmd in walk(prog.cmd):
            if cmd.subcommands:
                subs = " ".join(fq(s.path[-1]) for s in cmd.subcommands)
                subcmd_cases.append(
                    f"        case {fq(cmd.key)}\n            printf '%s\\n' {subs}"
                )
            valopts = [n for o in cmd.opts if o.kind is not None for n in o.names]
            if valopts:
                valopt_cases.append(
                    f"        case {fq(cmd.key)}\n            printf '%s\\n' "
                    + " ".join(map(fq, valopts))
                )

        for name in prog.names:
            completions.append(f"\n# {name}\ncomplete -c {fq(name)} -f")
            for cmd in walk(prog.cmd):
                # command paths only contain [\w -], so this quoting is safe
                head = f'complete -c {fq(name)} -n "__bugit_at {fq(cmd.key)}"'
                for o in cmd.opts:
                    completions.append(f"{head} {fish_opt_flags(o)}")
                for s in cmd.subcommands:
                    desc = f" -d {fq(s.help)}" if s.help else ""
                    completions.append(f"{head} -a {fq(s.path[-1])}{desc}")
                if cmd.args:
                    # fish can't tell positional args apart, use the first one
                    action = fish_value_action(cmd.args[0].kind, cmd.args[0].choices)
                    if action != "-f":
                        completions.append(f"{head} {action}")

    prog_cases = "\n".join(
        f"        case {' '.join(map(fq, p.names))}\n            set path {fq(p.root)}"
        for p in programs
    )
    subcmd_body = "\n".join(subcmd_cases)
    valopt_body = "\n".join(valopt_cases)
    completion_lines = "\n".join(completions)
    return f"""\
# {HEADER}
#
# Save this as a fish config snippet, for example:
#   bugit.completion fish > ~/.config/fish/conf.d/bugit.fish

function __bugit_subcmds --argument-names path
    switch $path
{subcmd_body}
    end
end

function __bugit_valopts --argument-names path
    switch $path
{valopt_body}
    end
end

# prints the subcommand path of the current command line, like "bugit-v2 jira"
function __bugit_path
    set -l tokens (commandline -opc)
    set -l path
    switch (string replace -r '.*/' '' -- $tokens[1])
{prog_cases}
        case '*'
            return 1
    end
    set -l expect 0
    set -l npos 0
    for t in $tokens[2..-1]
        if test $expect = 1
            set expect 0
            continue
        end
        if test "$t" = --
            break
        end
        if string match -q -- '-?*' $t
            if not string match -q -- '*=*' $t; and contains -- $t (__bugit_valopts $path)
                set expect 1
            end
            continue
        end
        if test $npos = 0; and contains -- $t (__bugit_subcmds $path)
            set path "$path $t"
            continue
        end
        set npos (math $npos + 1)
    end
    echo $path
end

function __bugit_at --argument-names want
    test "$(__bugit_path)" = "$want"
end
{completion_lines}
"""


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate shell completion scripts for the bugit snap apps"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit with 1 if the generated files are outdated instead of writing them",
    )
    ns = parser.parse_args()

    programs, errors = collect_programs()
    outputs = {
        BASH_FILE: gen_bash(programs),
        ZSH_FILE: gen_zsh(programs),
        FISH_FILE: gen_fish(programs),
    }

    for file, content in outputs.items():
        rel = file.relative_to(REPO_ROOT)
        if ns.check:
            if not file.exists() or file.read_text() != content:
                errors.append(f"{rel} is outdated, run tools/{Path(__file__).name}")
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content)
            print(f"Wrote {rel}")

    for e in errors:
        print(e, file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())

"""
Data model for attaching logs/comments to an existing bug instead of
creating a new one
"""

import time
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Final, Literal, Self
from uuid import UUID

from pydantic import BaseModel, Field

from bugit_v2.checkbox_utils.checkbox_session import CheckboxSession
from bugit_v2.checkbox_utils.models import SimpleCheckboxSubmission
from bugit_v2.checkbox_utils.submission_extractor import read_simple_submission
from bugit_v2.models.bug_report import BugReport, LogName

AttachSubmitterName = Literal["jira", "lp"]

ATTACH_PLACEHOLDER_COMMENT: Final = "Auto generated by bugit-v2"


@dataclass(slots=True, frozen=True)
class AttachmentRequest:
    """
    Logs, files and an optional comment to attach to an existing bug.
    Avoid attaching methods to this class unless it's a simple getter
    """

    request_id: UUID  # internal uuid, used for keeping track of auto saves
    submitter: AttachSubmitterName
    bug_id: str  # STELLA-123 for jira, 123456 for launchpad
    comment: str
    checkbox_session: CheckboxSession | None
    checkbox_submission: SimpleCheckboxSubmission | None
    job_id: str | None
    logs_to_include: Sequence[LogName] = field(default_factory=list[LogName])
    additional_files: Sequence[Path] = field(default_factory=list[Path])
    # for recovery only
    source: Literal["editor", "recovery"] = "editor"


# anything that can be fed to the log collectors
type CollectorInput = BugReport | AttachmentRequest


class SerializableAttachmentRequest(BaseModel):
    request_id: UUID
    last_updated_timestamp: int
    submitter: AttachSubmitterName
    bug_id: str
    comment: str
    checkbox_session: Path | None
    checkbox_submission: Path | None
    job_id: str | None
    logs_to_include: Sequence[LogName]
    additional_files: Sequence[Path] = Field(default_factory=list[Path])

    @classmethod
    def from_attachment_request(cls, r: AttachmentRequest) -> Self:
        return cls(
            request_id=r.request_id,
            last_updated_timestamp=int(time.time()),
            submitter=r.submitter,
            bug_id=r.bug_id,
            comment=r.comment,
            checkbox_session=r.checkbox_session
            and r.checkbox_session.session_path.absolute(),
            checkbox_submission=r.checkbox_submission
            and r.checkbox_submission.submission_path.absolute(),
            job_id=r.job_id,
            logs_to_include=r.logs_to_include,
            additional_files=r.additional_files,
        )

    def to_attachment_request(self) -> AttachmentRequest:
        return AttachmentRequest(
            request_id=self.request_id,
            submitter=self.submitter,
            bug_id=self.bug_id,
            comment=self.comment,
            checkbox_session=self.checkbox_session
            and CheckboxSession(self.checkbox_session),
            checkbox_submission=self.checkbox_submission
            and read_simple_submission(self.checkbox_submission),
            job_id=self.job_id,
            logs_to_include=self.logs_to_include,
            additional_files=self.additional_files,
            source="recovery",
        )
